/// Alias for backwards compatibility.
String getCraftImage(String? rawIdentifier) => getCraftImagePath(rawIdentifier);

/// Central helper mapping any craft name, ID, or URL to a unique offline craft asset.
String getCraftImagePath(String? rawIdentifier) {
  if (rawIdentifier == null || rawIdentifier.isEmpty) {
    return all110CraftImages[0];
  }

  // Sanitize any fragment anchor or query param e.g. .jpg#gi_bandhani_01
  final identifier = rawIdentifier.split('#').first.split('?').first.trim();
  if (identifier.isEmpty) {
    return all110CraftImages[0];
  }

  // Direct exact path check ONLY if the file actually exists in our bundle
  if (identifier.startsWith('assets/images/crafts/')) {
    if (all110CraftImages.contains(identifier) || _extraValidCraftImages.contains(identifier)) {
      return identifier;
    }
  }
  if (identifier.startsWith('assets/images/sample_crafts/')) {
    final filename = identifier.split('/').last;
    return getCraftImagePath(filename);
  }

  final lower = identifier.toLowerCase();
  final hash = identifier.hashCode.abs();

  // State Craft Direct Matches (AI Generated)
  if (lower.contains('kondapalli')) return 'assets/images/crafts/ap_kondapalli_bommalu.jpg';
  if (lower.contains('monpa') || lower.contains('apatani')) return 'assets/images/crafts/arunachal_monpa_paper.jpg';
  if (lower.contains('muga') || lower.contains('sualkuchi')) return 'assets/images/crafts/assam_muga_silk.jpg';
  if (lower.contains('madhubani') || lower.contains('mithila')) return 'assets/images/crafts/bihar_madhubani.jpg';
  if (lower.contains('bastar') || lower.contains('dhokra')) return 'assets/images/crafts/chhattisgarh_bastar_dhokra.jpg';
  if (lower.contains('kunbi') || lower.contains('azulejo')) return 'assets/images/crafts/goa_kunbi_weaving.jpg';
  if (lower.contains('patola') || lower.contains('patan')) return 'assets/images/crafts/gujarat_patan_patola.jpg';
  if (lower.contains('phulkari')) return 'assets/images/crafts/haryana_phulkari.jpg';
  if (lower.contains('kullu') || lower.contains('chamba')) return 'assets/images/crafts/hp_kullu_shawl.jpg';
  if (lower.contains('sohrai') || lower.contains('khovar')) return 'assets/images/crafts/jharkhand_sohrai.jpg';
  if (lower.contains('channapatna')) return 'assets/images/crafts/karnataka_channapatna.jpg';
  if (lower.contains('aranmula') || lower.contains('kannadi')) return 'assets/images/crafts/kerala_aranmula_kannadi.jpg';
  if (lower.contains('gond')) return 'assets/images/crafts/mp_gond_painting.jpg';

  // Craft Group Matching
  if (lower.contains('bandhani')) {
    return 'assets/images/crafts/bandhani_0${(hash % 5) + 1}.jpg';
  }
  if (lower.contains('patola')) {
    return 'assets/images/crafts/patola_0${(hash % 4) + 1}.jpg';
  }
  if (lower.contains('ajrakh')) {
    return 'assets/images/crafts/ajrakh_0${(hash % 3) + 1}.jpg';
  }
  if (lower.contains('rogan')) {
    return 'assets/images/crafts/rogan_art_0${(hash % 3) + 1}.jpg';
  }
  if (lower.contains('blue_pottery') || (lower.contains('pottery') && lower.contains('blue'))) {
    return 'assets/images/crafts/blue_pottery_0${(hash % 5) + 1}.jpg';
  }
  if (lower.contains('meenakari')) {
    return 'assets/images/crafts/meenakari_0${(hash % 3) + 1}.jpg';
  }
  if (lower.contains('bagru')) {
    return 'assets/images/crafts/bagru_print_0${(hash % 3) + 1}.jpg';
  }
  if (lower.contains('sanganeri')) {
    return 'assets/images/crafts/sanganeri_print_0${(hash % 4) + 1}.jpg';
  }
  if (lower.contains('chanderi')) {
    return 'assets/images/crafts/chanderi_0${(hash % 5) + 1}.jpg';
  }
  if (lower.contains('gond') || lower.contains('warli')) {
    return 'assets/images/crafts/gond_painting_0${(hash % 5) + 1}.jpg';
  }
  if (lower.contains('chikan')) {
    return 'assets/images/crafts/chikankari_0${(hash % 5) + 1}.jpg';
  }
  if (lower.contains('banarasi')) {
    return 'assets/images/crafts/banarasi_silk_0${(hash % 5) + 1}.jpg';
  }
  if (lower.contains('kantha')) {
    return 'assets/images/crafts/kantha_0${(hash % 5) + 1}.jpg';
  }
  if (lower.contains('bankura') || lower.contains('terracotta') || lower.contains('dokra') || lower.contains('bidriware')) {
    return 'assets/images/crafts/bankura_terracotta_0${(hash % 5) + 1}.jpg';
  }
  if (lower.contains('pashmina') || lower.contains('tangaliya') || lower.contains('shawl') || lower.contains('kani')) {
    return 'assets/images/crafts/pashmina_0${(hash % 5) + 1}.jpg';
  }
  if (lower.contains('papier') || lower.contains('mache')) {
    return 'assets/images/crafts/papier_mache_0${(hash % 5) + 1}.jpg';
  }
  if (lower.contains('madhubani') || lower.contains('mithila')) {
    return 'assets/images/crafts/madhubani_0${(hash % 5) + 1}.jpg';
  }
  if (lower.contains('pattachitra')) {
    return 'assets/images/crafts/pattachitra_0${(hash % 5) + 1}.jpg';
  }
  if (lower.contains('filigree') || lower.contains('tarakasi')) {
    return 'assets/images/crafts/silver_filigree_0${(hash % 5) + 1}.jpg';
  }
  if (lower.contains('channapatna') || lower.contains('sankheda') || lower.contains('toy')) {
    return 'assets/images/crafts/channapatna_toys_0${(hash % 5) + 1}.jpg';
  }
  if (lower.contains('mysore')) {
    return 'assets/images/crafts/mysore_silk_0${(hash % 5) + 1}.jpg';
  }
  if (lower.contains('kanchipuram') || lower.contains('kalamkari')) {
    return 'assets/images/crafts/kanchipuram_silk_0${(hash % 5) + 1}.jpg';
  }
  if (lower.contains('tanjore') || lower.contains('thanjavur')) {
    return 'assets/images/crafts/tanjore_painting_0${(hash % 5) + 1}.jpg';
  }
  if (lower.contains('bamboo')) {
    return 'assets/images/crafts/bamboo_basket_0${(hash % 4) + 1}.jpg';
  }
  if (lower.contains('cane')) {
    return 'assets/images/crafts/cane_craft_0${(hash % 3) + 1}.jpg';
  }
  if (lower.contains('assam') || lower.contains('muga') || lower.contains('eri')) {
    return 'assets/images/crafts/assam_silk_0${(hash % 3) + 1}.jpg';
  }

  // Deterministic fallback across the full 110 unique image pack
  return all110CraftImages[hash % all110CraftImages.length];
}

/// Helper Widget that builds a craft image from a local asset
Widget buildCraftImage(
  String? identifier, {
  double? width,
  double? height,
  BoxFit fit = BoxFit.cover,
}) {
  return Image.asset(
    getCraftImagePath(identifier),
    width: width,
    height: height,
    fit: fit,
    errorBuilder: (context, error, stackTrace) {
      return Image.asset(
        all110CraftImages[0],
        width: width,
        height: height,
        fit: fit,
      );
    },
  );
}
