  ];

  static Future<List<FestivalCollectionModel>> getActiveCollections() async {
    for (final base in _backendCandidates) {
      try {
        final url = Uri.parse('$base/collections');
        final resp = await http.get(url).timeout(const Duration(seconds: 3));
        if (resp.statusCode == 200) {
          final List list = jsonDecode(resp.body);
          if (list.isNotEmpty) {
            return list.map((e) => FestivalCollectionModel.fromJson(e as Map<String, dynamic>)).toList();
          }
        }
      } catch (_) {}
    }
    return getFallbackCollections();
  }

  static Future<FestivalCollectionModel> getCollectionBySlug(String slug) async {
    final cleanSlug = slug.toLowerCase().trim();
    for (final base in _backendCandidates) {
      try {
        final url = Uri.parse('$base/collections/$cleanSlug');
        final resp = await http.get(url).timeout(const Duration(seconds: 3));
        if (resp.statusCode == 200) {
          final data = jsonDecode(resp.body);
          return FestivalCollectionModel.fromJson(data as Map<String, dynamic>);
        }
      } catch (_) {}
    }
    
    // Fallback if offline
    final fallbacks = getFallbackCollections();
    try {
      return fallbacks.firstWhere(
        (c) => c.slug.toLowerCase() == cleanSlug || cleanSlug.contains(c.slug.toLowerCase()) || c.slug.toLowerCase().contains(cleanSlug),
      );
    } catch (_) {
      return fallbacks.first;
    }
  }

