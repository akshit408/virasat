  StateModel getStateDetails(String identifier) {
    final clean = identifier.toUpperCase().trim();
    if (_statesData.containsKey(clean)) return _statesData[clean]!;
    for (final entry in _statesData.entries) {
      if (entry.value.name.toLowerCase() == identifier.toLowerCase() ||
          entry.value.id.toLowerCase() == identifier.toLowerCase()) {
        return entry.value;
      }
    }
    return _statesData['IN-GJ']!;
  }

  
  /// Returns all products across all 28 states & UTs
  List<GiProductModel> getAllProducts() {
    final list = <GiProductModel>[];
    for (final prods in _stateProductsMap.values) {
      list.addAll(prods);
    }
    return list;
  }

  Map<String, StateModel> getAllStates() => Map.unmodifiable(_statesData);

  /// Returns unique products for a specific state based on user exact craft list
  List<GiProductModel> getPopularCraftsForState(String identifier) {
    final state = getStateDetails(identifier);
    if (_stateProductsMap.containsKey(state.id)) {
      return _stateProductsMap[state.id]!;
    }
    return _stateProductsMap['IN-GJ']!;
  }

  /// Hidden Gems for state
  List<GiProductModel> getHiddenGemsForState(String identifier) {
    final products = getPopularCraftsForState(identifier);
    if (products.length >= 4) {
      return products.sublist(2);
    }
    return products;
  }

  /// Featured Master Artisans for State
  List<Map<String, String>> getFeaturedArtisansForState(String identifier) {
    final state = getStateDetails(identifier);
    if (_stateArtisansMap.containsKey(state.id)) {
      return _stateArtisansMap[state.id]!;
    }
    return _stateArtisansMap['IN-GJ']!;
  }

  /// District Craft Origins for State
  List<Map<String, String>> getDistrictCraftOrigins(String identifier) {
    final products = getPopularCraftsForState(identifier);
    final list = <Map<String, String>>[];
    for (int i = 0; i < products.length; i++) {
      list.add({
        'district': products[i].district,
        'craft': products[i].name,
        'status': 'GI Certified Origin',
      });
    }
    return list;
  }
